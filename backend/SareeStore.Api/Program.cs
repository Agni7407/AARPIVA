static async Task EnsureCategoryImageSchemaAsync(AppDbContext db)
{
    await db.Database.ExecuteSqlRawAsync("""
        ALTER TABLE "Categories" ADD COLUMN IF NOT EXISTS "ImageMode" text NOT NULL DEFAULT 'auto';
        ALTER TABLE "Categories" ADD COLUMN IF NOT EXISTS "ImageUrl" text NULL;
        UPDATE "Categories" SET "ImageMode" = 'auto' WHERE "ImageMode" IS NULL OR BTRIM("ImageMode") = '';
        ALTER TABLE "Categories" ALTER COLUMN "ImageMode" SET DEFAULT 'auto';
        ALTER TABLE "Categories" ALTER COLUMN "ImageMode" SET NOT NULL;
    """);
}

static async Task EnsureSizeInventorySchemaAsync(AppDbContext db)
{
    await db.Database.ExecuteSqlRawAsync("""
        ALTER TABLE "Categories" ADD COLUMN IF NOT EXISTS "RequiresSize" boolean NOT NULL DEFAULT FALSE;
        ALTER TABLE "Categories" ADD COLUMN IF NOT EXISTS "SizeOptionsJson" text NOT NULL DEFAULT '[]';
        ALTER TABLE "Categories" ADD COLUMN IF NOT EXISTS "SizeGuideJson" text NOT NULL DEFAULT '{{}}';
        CREATE TABLE IF NOT EXISTS "ProductSizeVariants" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ProductId" integer NOT NULL,
            "SizeCode" text NOT NULL,
            "Stock" integer NOT NULL DEFAULT 0,
            "IsEnabled" boolean NOT NULL DEFAULT TRUE,
            CONSTRAINT "CK_ProductSizeVariants_Stock" CHECK ("Stock" >= 0),
            CONSTRAINT "FK_ProductSizeVariants_Products_ProductId" FOREIGN KEY ("ProductId") REFERENCES "Products"("Id") ON DELETE CASCADE);
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_ProductSizeVariants_ProductId_SizeCode" ON "ProductSizeVariants"("ProductId", "SizeCode");
        DO $$ BEGIN
            IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'CK_ProductSizeVariants_Stock' AND conrelid = '"ProductSizeVariants"'::regclass) THEN
                ALTER TABLE "ProductSizeVariants" ADD CONSTRAINT "CK_ProductSizeVariants_Stock" CHECK ("Stock" >= 0);
            END IF;
            IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_ProductSizeVariants_Products_ProductId' AND conrelid = '"ProductSizeVariants"'::regclass) THEN
                ALTER TABLE "ProductSizeVariants" ADD CONSTRAINT "FK_ProductSizeVariants_Products_ProductId" FOREIGN KEY ("ProductId") REFERENCES "Products"("Id") ON DELETE CASCADE;
            END IF;
        END $$;
        ALTER TABLE "CartItems" ADD COLUMN IF NOT EXISTS "SizeCode" text NOT NULL DEFAULT '';
        DROP INDEX IF EXISTS "IX_CartItems_UserId_ProductId";
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_CartItems_UserId_ProductId_SizeCode" ON "CartItems"("UserId", "ProductId", "SizeCode");
        ALTER TABLE "OrderItems" ADD COLUMN IF NOT EXISTS "SizeCode" text NOT NULL DEFAULT '';
        ALTER TABLE "OrderItems" ADD COLUMN IF NOT EXISTS "RequiresSize" boolean NOT NULL DEFAULT FALSE;
        ALTER TABLE "Orders" ADD COLUMN IF NOT EXISTS "StockReserved" boolean NOT NULL DEFAULT FALSE;
        ALTER TABLE "Orders" ADD COLUMN IF NOT EXISTS "ReservationExpiresAt" timestamp with time zone NULL;
        ALTER TABLE "Orders" ADD COLUMN IF NOT EXISTS "RefundReference" text NULL;
        ALTER TABLE "Orders" ADD COLUMN IF NOT EXISTS "RefundNote" text NULL;
        ALTER TABLE "Orders" ADD COLUMN IF NOT EXISTS "RefundResolvedAt" timestamp with time zone NULL;
    """);
}


