static async Task EnsureLegalSchemaAsync(AppDbContext db)
{
    await db.Database.ExecuteSqlRawAsync("""
        ALTER TABLE "Users" ADD COLUMN IF NOT EXISTS "TermsAcceptedAt" timestamp with time zone NULL;
        ALTER TABLE "Users" ADD COLUMN IF NOT EXISTS "TermsVersion" text NULL;
    """);
