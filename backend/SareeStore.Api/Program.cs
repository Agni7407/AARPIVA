            "OrderId" integer NOT NULL,
            "OrderItemId" integer NOT NULL,
            "UserId" integer NOT NULL,
            "Quantity" integer NOT NULL,
            "Reason" text NOT NULL,
            "Status" text NOT NULL DEFAULT 'Requested',
            "AdminNote" text NOT NULL DEFAULT '',
            "CreatedAt" timestamp with time zone NOT NULL,
            "UpdatedAt" timestamp with time zone NOT NULL
        );
        CREATE INDEX IF NOT EXISTS "IX_ReturnRequests_OrderId_OrderItemId_Status" ON "ReturnRequests" ("OrderId", "OrderItemId", "Status");
    """);
}

var app = builder.Build();

app.UseExceptionHandler(errorApp =>
{
    errorApp.Run(async context =>
    {
        context.Response.StatusCode = StatusCodes.Status500InternalServerError;
        await Results.Problem(
            statusCode: StatusCodes.Status500InternalServerError,
            title: "Unexpected server error.")
            .ExecuteAsync(context);
    });
});

app.UseForwardedHeaders(new ForwardedHeadersOptions
{
    ForwardedHeaders = ForwardedHeaders.XForwardedFor | ForwardedHeaders.XForwardedProto
});

if (app.Environment.IsDevelopment())
{
    app.UseSwagger();
    app.UseSwaggerUI();
}

app.UseCors("frontend");
app.UseRateLimiter();
app.UseAuthentication();
app.UseAuthorization();

app.MapHealthChecks("/health").AllowAnonymous();
app.MapControllers();

using (var scope = app.Services.CreateScope())
{
    var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
    await db.Database.EnsureCreatedAsync();
    await EnsureCategoryImageSchemaAsync(db);
    await EnsureEmailVerificationOtpSchemaAsync(db);
    await EnsurePasswordResetOtpSchemaAsync(db);
    await EnsureLegalSchemaAsync(db);
    await EnsureReturnRequestSchemaAsync(db);
    await EnsureCartSchemaAsync(db);
    await EnsureSizeInventorySchemaAsync(db);
    await EnsureDeliveryPricingSchemaAsync(db);

    var adminEmail = cfg["SeedAdmin:Email"];
    var adminPassword = cfg["SeedAdmin:Password"];
    if (!string.IsNullOrWhiteSpace(adminEmail) && !string.IsNullOrWhiteSpace(adminPassword))
    {
        var normalizedAdmin = adminEmail.Trim().ToLowerInvariant();
        var admin = await db.Users.FirstOrDefaultAsync(x => x.Email == normalizedAdmin);
        if (admin is null)
        {
            db.Users.Add(new AppUser
            {
                Name = "Store Admin",
                Email = normalizedAdmin,
                PasswordHash = PasswordHasher.Hash(adminPassword),
                IsEmailVerified = true,
                Role = UserRole.Admin
            });
            await db.SaveChangesAsync();
        }
    }
}

app.Run();
